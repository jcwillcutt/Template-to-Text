// The extension must ship as ONE file. These tests build it from src/ and check that the result is a faithful,
// self-contained concatenation: no leftover module syntax, every identifier resolves, and the engine inside the
// bundle behaves exactly like the engine imported from src/.
import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import ts from 'typescript';
// @ts-expect-error -- plain ESM script without types
import { build, ORDER } from '../../scripts/build.mjs';
import { run, type RunOpts } from '../helpers/differential';
import { makeNote, makeProducts } from '../helpers/fixtures';
import * as srcEngine from '../../src/engine/index';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const bundle: string = build();

function parse(text: string): ts.SourceFile {
  return ts.createSourceFile('bundle.tsx', text, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TSX);
}

describe('bundle shape', () => {
  const sf = parse(bundle);
  it('is a single self-contained file with the generated banner', () => {
    expect(bundle.startsWith('// GENERATED by scripts/build.mjs')).toBe(true);
  });
  it('imports only from preact', () => {
    const specs = sf.statements.filter(ts.isImportDeclaration).map((s) => (s.moduleSpecifier as ts.StringLiteral).text);
    expect(specs.sort()).toEqual(['preact', 'preact/hooks']);
  });
  it('has exactly one export: the default entry point', () => {
    const exported = sf.statements.filter((s) => {
      const mods = ts.canHaveModifiers(s) ? ts.getModifiers(s) : undefined;
      return ts.isExportAssignment(s) || ts.isExportDeclaration(s) || mods?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
    });
    expect(exported).toHaveLength(1);
    expect(ts.isExportAssignment(exported[0])).toBe(true);
  });
  it('contains no relative imports and no "// ====" module headers inside code strings', () => {
    expect(bundle).not.toMatch(/from '\.{1,2}\//);
  });
  it('has no syntax errors', () => {
    const diagnostics = (ts.transpileModule(bundle, { reportDiagnostics: true, fileName: 'bundle.tsx', compilerOptions: { jsx: ts.JsxEmit.Preserve, target: ts.ScriptTarget.ES2022 } }).diagnostics ?? []).filter(
      (d) => d.category === ts.DiagnosticCategory.Error,
    );
    expect(diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n'))).toEqual([]);
  });
  it('every identifier resolves (the only free name is the Shopify global)', () => {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'bundle-'));
    const file = path.join(tmp, 'bundle.tsx');
    fs.writeFileSync(file, bundle);
    const program = ts.createProgram([file], {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      jsx: ts.JsxEmit.Preserve,
      noEmit: true,
      skipLibCheck: true,
      lib: ['lib.es2022.d.ts', 'lib.dom.d.ts'],
      types: [],
      noResolve: true,
    });
    const free = new Set<string>();
    for (const d of ts.getPreEmitDiagnostics(program)) {
      if (d.code === 2304 || d.code === 2552) free.add(/Cannot find name '([^']+)'/.exec(ts.flattenDiagnosticMessageText(d.messageText, '\n'))?.[1] ?? '?');
    }
    expect([...free]).toEqual(['shopify']);
  });
  it('is deterministic', () => {
    expect(build()).toBe(bundle);
  });
  it('lists every source module exactly once, and every module in src/ is either listed or a test-only entry point', () => {
    expect(new Set(ORDER).size).toBe(ORDER.length);
    for (const f of ORDER) expect(fs.existsSync(path.join(ROOT, f)), f).toBe(true);
    const all: string[] = [];
    const walk = (d: string): void => {
      for (const e of fs.readdirSync(path.join(ROOT, d), { withFileTypes: true })) {
        const rel = `${d}/${e.name}`;
        if (e.isDirectory()) walk(rel);
        else if (/\.(ts|tsx)$/.test(e.name)) all.push(rel);
      }
    };
    walk('src');
    const unlisted = all.filter((f) => !ORDER.includes(f)).sort();
    // src/engine/index.ts is the test/typecheck entry point (re-exports only); everything else must ship.
    expect(unlisted).toEqual(['src/engine/index.ts']);
  });
});

describe('the engine inside the bundle behaves like the engine in src/', () => {
  // Load the bundle in a vm with the UI libraries stubbed, exposing the engine entry points.
  const js = ts.transpileModule(bundle + '\nexport const __engine = { planOutputFiles, buildZipBase64 };\n', {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX },
  }).outputText;
  const mod = { exports: {} as any };
  const stubs: Record<string, unknown> = {
    preact: { render() {} },
    'preact/hooks': { useState() {}, useEffect() {}, useMemo() {}, useRef() {} },
    'react/jsx-runtime': { jsx() {}, jsxs() {}, Fragment() {} },
  };
  vm.runInContext(js, vm.createContext({ module: mod, exports: mod.exports, require: (id: string) => stubs[id], console, setTimeout, Date, Math, Uint8Array, shopify: {} }));

  it('exports a default entry point that mounts the UI', () => {
    expect(typeof mod.exports.default).toBe('function');
    expect(() => mod.exports.default()).toThrow(/document/); // the stubbed environment has no DOM; it reached render(<Extension/>, document.body)
  });
  it('renders identically for a spread of templates and modes', () => {
    const products = makeProducts(5, { variants: 2 });
    const notes = [makeNote('n1'), makeNote('n2', 2)];
    const bodies = [
      '{{ product.title }}|{{ variant.sku }}',
      '{{#selection.foreach p, i=0}}{{ #if={{ = {{i}}%2 }}==0 }}E{{ #else }}O{{ /if }}{{ product.handle }};{{/selection.foreach}}',
      '{{ x = 3 }}{{ #if={{ x }} > 2 }}big{{ /if }}{{ #repeat=2 }}ab{{/repeat}}{{#wrap=4, delineator=|}}hello world{{/wrap}}',
    ];
    for (const body of bodies) {
      for (const fileBreak of ['variant', 'product', 'selection', 'object', 'note'] as const) {
        const o: RunOpts = { products, notes, fileBreak };
        expect(run(mod.exports.__engine, body, o)).toEqual(run(srcEngine, body, o));
      }
    }
  });
  it('zips identically', () => {
    const entries = [{ name: 'a.txt', content: 'é😀' }];
    expect(mod.exports.__engine.buildZipBase64(entries)).toBe(srcEngine.buildZipBase64(entries));
  });
});

describe('build script rules', () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'build-rules-'));
  const w = (name: string, text: string): string => {
    fs.writeFileSync(path.join(tmp, name), text);
    return name;
  };
  it('strips relative imports and inline exports, keeps the default export', () => {
    const a = w('a.ts', "export const A = 1;\nexport function f() { return A; }\nexport interface T { x: number }\n");
    const b = w('b.ts', "import { A, f } from './a';\nexport default () => f() + A;\n");
    const out: string = build([a, b], tmp);
    expect(out).toContain('const A = 1;');
    expect(out).toContain('function f()');
    expect(out).toContain('interface T');
    expect(out).not.toMatch(/export (const|function|interface)/);
    expect(out).toContain('export default () => f() + A;');
    expect(out).not.toContain("from './a'");
  });
  it('merges and hoists external imports', () => {
    const a = w('c.ts', "import { x } from 'lib';\nexport const C = x;\n");
    const b = w('d.ts', "import { y } from 'lib';\nimport Def from 'other';\nexport default () => [C, y, Def];\n");
    const out: string = build([a, b], tmp);
    expect(out).toContain("import { x, y } from 'lib';");
    expect(out).toContain("import Def from 'other';");
    expect(out.indexOf('import')).toBeLessThan(out.indexOf('const C'));
  });
  it('fails loudly on a duplicate top-level name', () => {
    const a = w('e.ts', 'export const Same = 1;\n');
    const b = w('f.ts', 'export function Same() {}\nexport default () => 1;\n');
    expect(() => build([a, b], tmp)).toThrow(/Duplicate top-level name 'Same'/);
  });
  it('fails on export lists and re-exports (they cannot be flattened safely)', () => {
    const a = w('g.ts', 'const q = 1;\nexport { q };\nexport default () => 1;\n');
    expect(() => build([a], tmp)).toThrow(/not allowed/);
    const b = w('h.ts', "export * from './g';\nexport default () => 1;\n");
    expect(() => build([b], tmp)).toThrow(/not allowed/);
  });
  it('requires exactly one default export', () => {
    expect(() => build([w('i.ts', 'export const A1 = 1;\n')], tmp)).toThrow(/exactly one 'export default'/);
    expect(() => build([w('j.ts', 'export default () => 1;\n'), w('k.ts', 'export default () => 2;\n')], tmp)).toThrow(/exactly one 'export default'/);
  });
  it('treats function overloads as one name', () => {
    const a = w('l.ts', 'export function ov(a: string): string;\nexport function ov(a: number): number;\nexport function ov(a: any): any { return a; }\nexport default () => ov(1);\n');
    expect(() => build([a], tmp)).not.toThrow();
  });
});
